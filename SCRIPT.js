function removerAcentos(texto) {
  return String(texto || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

function estaEmPerigo(animal) {
  const estado = removerAcentos(animal.conservacao);
  return estado.includes("perigo") || estado.includes("vulneravel") || estado.includes("ameacado");
}

function animaisFiltrados() {
  return animais
    .map(function(animal, index) { return { animal, index }; })
    .filter(function(item) {
      const combinaCategoria = filtroCategoria === null || item.animal.categoria === filtroCategoria;
      const combinaPesquisa = removerAcentos(item.animal.nome).includes(removerAcentos(textoPesquisa));
      return combinaCategoria && combinaPesquisa;
    });
}

function atualizarContadores() {
  document.getElementById("totalAnimais").textContent = animais.length;
  document.getElementById("totalMamiferos").textContent = animais.filter(a => a.categoria === "Mamífero").length;
  document.getElementById("totalAves").textContent = animais.filter(a => a.categoria === "Ave").length;
  document.getElementById("totalRepteis").textContent = animais.filter(a => a.categoria === "Réptil").length;
  document.getElementById("totalPerigo").textContent = animais.filter(estaEmPerigo).length;

  const totalVisivel = animaisFiltrados().length;
  document.getElementById("contadorAnimais").textContent = "Animais encontrados: " + totalVisivel;
}

